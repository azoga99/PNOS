# -*- coding: utf-8 -*-
"""
Тесты правил дат Д1 и Д2 (см. «для обучени/РАЗМЕТКА.md», §5).

Данные — реальные: блоки подписей реестров п.2763, п.2775 и п.2701 и акты
222-1-179 / 222-1-121.
"""

from repair.dates import act_date, find_dates, latest_date


# ─── Д1: дата выполнения работ ─────────────────────────────────────────

def test_latest_date_ignores_row_order():
    """п.2763: «Сдал» пустая, штамп 15.04 у «Принял», рукопись 16.04 у
    «Проверил». Берём самую позднюю, а не строку «Сдал»."""
    строки = [
        "Объем выполненных работ подтвержден: Механик уст.39-40  15 АПР 2026",
        "Сдал: Начальник ПТО Сыропятов А.В.",
        "Проверил: Инженер ОТН  16.04.2026",
        "Принял: Механик уст.39-40  15 АПР 2026",
    ]
    assert latest_date(строки) == "16.04.2026"


def test_latest_date_other_row_order():
    """п.2701 (ТП Инжиниринг): порядок строк Сдал / Принял / Проверил."""
    строки = ["Сдал: Инженер 2 категории 09.04.2026",
              "Принял: Механик УДГП",
              "Проверил: Инженер ОТН 09.04.2026"]
    assert latest_date(строки) == "09.04.2026"


def test_latest_date_none_when_handwritten():
    """Обычный случай: даты рукописные, OCR вернул только заголовки."""
    строки = ["Выданы замечания:", "(должность)", "(подпись)", "(дата)"]
    assert latest_date(строки) is None


def test_stamp_with_split_day():
    """Штамп OCR отдаёт с разорванным днём: «1 5 АПР 2026»."""
    assert find_dates("1 5 АПР 2026") == find_dates("15.04.2026")


def test_word_date():
    assert latest_date("16 апреля 2026 г.") == "16.04.2026"


def test_impossible_date_skipped():
    assert find_dates("32.13.2026") == []


# ─── Д2: дата акта ─────────────────────────────────────────────────────

def test_act_date_prefers_grif():
    assert act_date("24.03.2026",
                    "222-1-121 №122 39-40 30.03.2026.pdf") == "24.03.2026"


def test_act_date_falls_back_to_filename():
    """Гриф не распознан (день от руки) — берём дату из имени файла акта."""
    assert act_date("", "222-1-121 №122 39-40 24.03.2026.pdf") == "24.03.2026"


def test_act_date_partial_grif_yields_to_filename():
    """«.03.2026» — день грифа не прочитан; полная дата имени файла надёжнее."""
    assert act_date(".03.2026",
                    "222-1-121 №122 39-40 24.03.2026.pdf") == "24.03.2026"


def test_act_date_keeps_partial_when_no_filename_date():
    assert act_date(".03.2026", "ИД по Акту ОТН №222-1-143,121.pdf") == ".03.2026"


def test_act_date_empty_when_nothing_known():
    assert act_date("", "скан 001.pdf") == ""
