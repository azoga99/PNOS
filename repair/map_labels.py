# -*- coding: utf-8 -*-
"""
Поиск подписей сечений на коррозионной карте.

Зачем: чтобы сотрудник не искал сечение глазами. Если известно, где на карте
подпись каждого сечения, программа сама подводит к нужному месту, сама
подставляет новое значение и сама показывает «до/после».

Как это работает и почему именно так:

* **Карта распознаётся целиком, одним вызовом OCR.** Windows OCR возвращает
  слова вместе с рамками — этого достаточно: подпись сечения выглядит как
  «112 (5.9)», то есть число, а за ним значение в скобках. На карте п.2763
  (2970×4200, около 125 сечений) полный проход занимает полсекунды и находит
  14 из 16 подписей, проверенных глазами.
* **Подпись опознаётся по ЦВЕТУ номера, а не по читаемости значения.** Раньше
  требовалось, чтобы значение распозналось цифрами — «(5.9)». В мелком
  чертёжном курсиве Windows OCR читает его кириллицей: «(3.0)» приходит как
  «(ЗО», «(3.5)» — «(ЗЯ», «(3.3)» — «(ЗУ». Каждая четвёртая подпись на карте
  п.2688 отбрасывалась, хотя номер сечения прочитан верно. Текст значения при
  этом никому не нужен: при правке оно вырезается геометрией
  (`find_value_span`). Поэтому доказательством служит другое — подписи сечений
  нарисованы цветной краской (бордовой, оранжевой, синей, голубой), а числа в
  штампе, в таблице элементов и в пояснениях к чертежу — чёрные.
  Замер по восьми рабочим листам семи пунктов: 487 → 529 распознанных сечений,
  ни одно из прежних не потеряно.
* **Выращивать рамки по цветной маске оказалось хуже.** Первая версия искала
  подписи по маске разметки и растила рамки из затравок: рамки слипались с
  трубопроводом и соседними подписями, номера читались неверно, и в выдаче
  один и тот же номер появлялся десятки раз. Этот путь отброшен.
* **Несколько масштабов — для полноты.** На каждом масштабе OCR теряет свои
  подписи (при 1.0 не нашлись 110 и 112, при 1.5 — 112 и 116), поэтому
  результаты объединяются.
* **Значение в скобках распознаётся плохо** («(5.9)» → «(59)») и как текст не
  используется: его всё равно предстоит заменить, а вырезает его геометрия
  (`find_value_span`).
* **Известное ограничение: номер иногда читается неверно.** OCR теряет цифру
  («49 (8.3)» → «4») или приписывает лишнюю («1 (8.0)» → «41»), и тогда на
  одном месте оказываются две подписи с разными номерами. На п.2763 таких
  мест три из 112. Выбрать верное правилом не удалось: ни число масштабов, на
  которых подпись найдена, ни длина номера не указывают на правильный вариант
  (проверено на всех трёх). Ошибка не тихая — страница показывает «мест: N,
  выберите», и сотрудник видит карту.

Слой чистый (numpy + Pillow + Windows OCR), Qt не знает.
"""

from __future__ import annotations

import re
from dataclasses import dataclass, field

import numpy as np

from repair.map_editor import BBox

# Номер сечения: 1–3 цифры отдельным словом.
_NUM_RE = re.compile(r"^(\d{1,3})$")
# Значение замера: «(5.9)», OCR часто теряет точку или закрывающую скобку.
# Как ТЕКСТ значение не проверяется (см. `_value_like`) — шаблон остался для
# справки и для пометки «значение прочиталось цифрами».
_VAL_RE = re.compile(r"^\(\s*(\d{1,3})[.,]?(\d)?\)?$")
# Номер и значение, слипшиеся в одно слово: «20(3.61», «8(37».
_GLUED_RE = re.compile(r"^(\d{1,3})\s*[(\[]\s*\S+$")
# Номера сечений не бывают больше этого — отсекает числа из штампа и таблицы.
MAX_SECTION = 500
# Длиннее этого короткий токен уже не похож на «(V.V)».
VALUE_MAX_CHARS = 5
#: Цифр в значении: «(12.4)» — три, больше не бывает. Отсекает случай, когда
#: OCR теряет скобки у чужого значения и склеивает его с соседней подписью:
#: на карте п.2775 «(4.7) 78 (6.1)» давало номер «47» со значением «786.1».
VALUE_MAX_DIGITS = 3
# Насколько далеко вправо от номера может стоять значение (в высотах номера).
VALUE_MAX_GAP = 2.0
# Масштабы распознавания: на каждом OCR теряет свои подписи, объединение даёт
# заметно больше (на карте п.2763: 100 подписей при двух масштабах, 107 при трёх).
SCALES = (1.0, 1.5, 2.0)
# У Windows OCR есть предел размера изображения (MaxImageDimension): карта
# 2970×4200 при масштабе 2.5 его превышает, и вызов падает с WinError.
MAX_OCR_DIM = 9800
# Две подписи с одним номером ближе этого расстояния — одна и та же подпись,
# найденная на разных масштабах.
SAME_LABEL_PX = 30


@dataclass
class MapLabel:
    """Подпись сечения на карте: «NN (V.V)»."""
    number: int
    point: tuple[int, int]        # точка внутри номера — для render_value
    bbox: BBox                    # рамка подписи целиком
    value_bbox: BBox | None = None   # рамка части «(V.V)» — её и заменяют
    value_text: str = ""          # как OCR прочитал значение (справочно)
    scales: list = field(default_factory=list)   # на каких масштабах найдена

    @property
    def center(self) -> tuple[int, int]:
        return ((self.bbox.x1 + self.bbox.x2) // 2,
                (self.bbox.y1 + self.bbox.y2) // 2)


def _word_box(wd: dict, scale: float) -> BBox:
    return BBox(int(wd["x"] / scale), int(wd["y"] / scale),
                int((wd["x"] + wd["w"]) / scale),
                int((wd["y"] + wd["h"]) / scale))


#: Насыщенность, начиная с которой цвет считается цветным, а не серым.
INK_SAT = 45
#: Меньше стольких пикселей чернил — судить не о чем.
MIN_INK_PX = 12


def ink_color(arr: np.ndarray, box: BBox) -> tuple | None:
    """
    Цвет, которым нарисован текст в рамке: самый частый непрозрачный цвет.

    Именно САМЫЙ ЧАСТЫЙ, а не средний и не «есть ли цветные пиксели». Карта —
    экспорт с квантованной палитрой, и вокруг чёрных глифов рассыпан цветной
    дизер: у надписи «10(1)» на карте п.2704 чёрных пикселей 207, а цветных в
    ореоле 467. Проверка «цветных больше чёрных» на этом ломается, а мода —
    нет: тело глифа залито одним цветом палитры, ореол размазан по десятку.
    """
    zone = arr[max(0, box.y1):box.y2, max(0, box.x1):box.x2]
    if zone.size == 0:
        return None
    пиксели = zone.reshape(-1, 3).astype(int)
    чернила = пиксели[pixels_ink(пиксели)]
    if len(чернила) < MIN_INK_PX:
        return None
    ключи = (чернила[:, 0] << 16) | (чернила[:, 1] << 8) | чернила[:, 2]
    значения, счёт = np.unique(ключи, return_counts=True)
    top = int(значения[int(np.argmax(счёт))])
    return ((top >> 16) & 255, (top >> 8) & 255, top & 255)


#: Пиксель светлее этого по ВСЕМ каналам — бумага либо бледный дизер.
PAPER_MIN = 200


def pixels_ink(пиксели: np.ndarray) -> np.ndarray:
    """
    Маска «это чернила, а не бумага» для плоского массива пикселей.

    Порог по минимальному каналу, а не по максимальному: у оранжевой подписи
    (255, 144, 60) и у ярко-красной (255, 0, 0) максимум равен 255, и проверка
    по максимуму выбрасывала их целиком — цветные подписи оставались вовсе без
    чернил, а решение принимал тёмный дизер вокруг них.
    """
    return пиксели.min(axis=1) < PAPER_MIN


def is_markup_number(arr: np.ndarray, box: BBox) -> bool:
    """
    Номер нарисован цветной разметкой, а не чёрным.

    Это и есть главный признак подписи сечения. Подписи на карте бордовые,
    оранжевые, синие и голубые; числа в штампе, в таблице элементов, в
    обозначениях диаметров и в пояснениях к чертежу — чёрные. Признак работает
    по пикселям и потому не зависит от того, что OCR увидел в тексте.
    """
    цвет = ink_color(arr, box)
    if цвет is None:
        return False
    return max(цвет) - min(цвет) > INK_SAT


def _value_like(token: str) -> bool:
    """
    Похож ли токен на значение замера «(V.V)» — по форме, не по содержанию.

    Проверять цифрами нельзя: в мелком чертёжном курсиве Windows OCR читает
    значение кириллицей — «(3.0)» приходит как «(ЗО», «(3.5)» как «(ЗЯ»,
    «(3.3)» как «(ЗУ», а иногда и вовсе без скобки — «ВО». Раньше такие
    подписи отбрасывались целиком, хотя номер сечения прочитан верно: на
    карте п.2688 так терялась каждая четвёртая подпись.

    Сам текст значения никому не нужен — при правке оно вырезается геометрией
    (`find_value_span`), а не по распознанному тексту.

    Одну зацепку всё же требуем: скобку, цифру или разделитель. Обе скобки и
    точку разом OCR не теряет, а вот текст из штампа сплошными буквами как раз
    так и выглядит: на карте п.2778 строка «116 т-и» (это «Т-11 в Т-12» из
    основной надписи, набранная тем же бордовым) проходила как подпись сечения
    №116 — и правка ушла бы прямо в штамп.
    """
    t = (token or "").strip()
    if not t:
        return False
    if t[0] in "([{":
        return True
    if len(t) > VALUE_MAX_CHARS:
        return False
    if "-" in t or "—" in t or "–" in t:
        return False                      # в «(V.V)» дефиса не бывает
    # Чистое число — это номер соседнего сечения, а не значение.
    if _NUM_RE.match(t):
        return False
    if sum(c.isdigit() for c in t) > VALUE_MAX_DIGITS:
        return False
    return any(c.isdigit() or c in ".,)]}" for c in t)


def _near(number: BBox, value: BBox) -> bool:
    """Значение стоит вплотную справа от номера, а не в другом конце строки."""
    предел = max(6.0, number.height() * VALUE_MAX_GAP)
    return -number.height() <= (value.x1 - number.x2) <= предел


def _labels_at_scale(arr: np.ndarray, scale: float) -> list[MapLabel]:
    from PIL import Image
    from repair.ocr import ocr_lines
    from repair.map_editor import find_value_span

    img = Image.fromarray(arr)
    if scale != 1.0:
        img = img.resize((int(img.width * scale), int(img.height * scale)),
                         Image.LANCZOS)
    out: list[MapLabel] = []
    for line in ocr_lines(np.array(img)):
        words = line.get("words") or []
        for i, wd in enumerate(words):
            текст = wd["t"].strip()
            слитно = _GLUED_RE.match(текст)
            m = _NUM_RE.match(текст) or слитно
            if not m:
                continue
            номер = int(m.group(1))
            if not (1 <= номер <= MAX_SECTION):
                continue
            nb = _word_box(wd, scale)
            # Главный признак подписи — цветная краска номера. Он же заменяет
            # прежнюю проверку значения по цифрам: чёрные числа из штампа и
            # таблицы отсекаются надёжнее, чем ею.
            if not is_markup_number(arr, nb):
                continue

            if слитно:
                # Номер и значение в одном слове: рамку значения даёт не OCR,
                # а геометрия — по наибольшему пробелу внутри подписи.
                out.append(MapLabel(
                    number=номер, point=((nb.x1 + nb.x2) // 2, (nb.y1 + nb.y2) // 2),
                    bbox=nb, value_bbox=find_value_span(arr, nb),
                    value_text=текст, scales=[scale]))
                continue

            # Подпись обязана иметь значение справа: иначе это номер сечения
            # без замера (такие на карте есть) — править в нём нечего.
            if i + 1 >= len(words):
                continue
            зн = words[i + 1]["t"].strip()
            vb = _word_box(words[i + 1], scale)
            if not _value_like(зн) or not _near(nb, vb):
                continue
            out.append(MapLabel(
                number=номер,
                point=((nb.x1 + nb.x2) // 2, (nb.y1 + nb.y2) // 2),
                bbox=BBox(min(nb.x1, vb.x1), min(nb.y1, vb.y1),
                          max(nb.x2, vb.x2), max(nb.y2, vb.y2)),
                value_bbox=vb, value_text=зн, scales=[scale]))
    return out


def find_labels(arr: np.ndarray, scales=SCALES, log=None) -> list[MapLabel]:
    """
    Найти подписи сечений на карте. Возвращает список, отсортированный сверху
    вниз. Один номер может встретиться несколько раз — это нормально
    (одинаковые участки), выбирать место правки должен сотрудник.
    """
    h, w = arr.shape[:2]
    предел = MAX_OCR_DIM / max(h, w)
    годные = [s for s in scales if s <= предел]
    if log and len(годные) < len(scales):
        log(f"Масштабы больше {предел:.1f} пропущены: карта {w}×{h}, "
            f"Windows OCR не берёт изображения крупнее {MAX_OCR_DIM} px")

    найдено: list[MapLabel] = []
    for scale in годные:
        порция = _labels_at_scale(arr, scale)
        добавлено = 0
        for lb in порция:
            двойник = next(
                (x for x in найдено if x.number == lb.number
                 and abs(x.point[0] - lb.point[0]) <= SAME_LABEL_PX
                 and abs(x.point[1] - lb.point[1]) <= SAME_LABEL_PX), None)
            if двойник is not None:
                двойник.scales.append(scale)
                continue
            найдено.append(lb)
            добавлено += 1
        if log:
            log(f"Карта, масштаб {scale}: подписей {len(порция)}, "
                f"новых {добавлено}")

    найдено.sort(key=lambda l: (l.bbox.y1, l.bbox.x1))
    if log:
        log(f"Карта: всего подписей {len(найдено)}, "
            f"разных сечений {len({l.number for l in найдено})}")
    return найдено


def labels_by_number(labels: list[MapLabel]) -> dict[int, list[MapLabel]]:
    """
    Подписи по номеру сечения.

    Список, а не одна подпись: один и тот же номер на карте встречается
    несколько раз (одинаковые переходы, повторяющиеся участки), и выбирать,
    какое именно место править, должен сотрудник.
    """
    out: dict[int, list[MapLabel]] = {}
    for lb in labels:
        out.setdefault(lb.number, []).append(lb)
    for номер in out:
        out[номер].sort(key=lambda l: (l.bbox.y1, l.bbox.x1))
    return out
