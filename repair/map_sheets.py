# -*- coding: utf-8 -*-
"""
Коррозионная карта из нескольких листов: какие файлы править и где искать
сечение.

В «Первичке» пункта лежат парами исходник ОТН и рабочая карта:

    2763..png    2763.png              — карта в один лист
    2704._1.png  2704_1.png            — лист 1
    2704._2.png  2704_2.png            — лист 2

Исходник отличается лишней точкой перед суффиксом. Он нарисован синим, разметки
толщинометрии на нём нет, и трогать его нельзя — правится только рабочая карта
с красной разметкой. Прежнее правило отбрасывало лишь имена, кончающиеся на
«..png», поэтому на многолистовом пункте выбирался `2704._1.png` (точка
сортируется раньше подчёркивания) — то есть как раз исходник, и второй лист
модуль не видел вовсе.

Имя карты не обязано совпадать с номером пункта: у п.2758 карта называется
`3024.png`, у п.2760 — `2680.png`. Поэтому опознаём по форме имени, а не по
номеру.

Слой чистый: ни Qt, ни numpy, ни OCR.
"""

from __future__ import annotations

import os
import re

#: Хвост номера листа в имени рабочей карты: «2704_2.png» → 2.
_SHEET_RE = re.compile(r"_(\d+)$")

#: Меньше этого числа распознанных подписей — лист не считается рабочей картой.
#: С запасом: у исходников ОТН находится 0–1 подпись (артефакт штампа), у
#: рабочих листов — от 66 (замеры по всей длине трубопровода).
MIN_SECTION_LABELS = 5


def is_working_map(filename: str) -> bool:
    """
    Рабочая ли это карта (её правим) или исходник ОТН (не трогаем).

    Признак — точка внутри имени: у исходника она есть («2763..png»,
    «2704._1.png»), у рабочей карты нет («2763.png», «2704_1.png»).
    """
    name = os.path.basename(filename or "")
    if not name.lower().endswith(".png"):
        return False
    return "." not in os.path.splitext(name)[0]


def sheet_number(filename: str) -> int:
    """Номер листа из имени: «2704_2.png» → 2, «2763.png» → 1."""
    stem = os.path.splitext(os.path.basename(filename or ""))[0]
    m = _SHEET_RE.search(stem)
    return int(m.group(1)) if m else 1


def working_map_files(names) -> list[str]:
    """
    Рабочие листы карты по порядку.

    Сортировка по числу, а не по строке: «_10» должен идти после «_9».
    """
    рабочие = [n for n in (names or []) if is_working_map(n)]
    return sorted(рабочие, key=lambda n: (sheet_number(n), os.path.basename(n)))


def original_map_file(filename: str) -> str:
    """
    Имя исходника ОТН для рабочего листа: «2763.png» → «2763..png»,
    «2704_1.png» → «2704._1.png».

    Точка ставится перед суффиксом листа, а не в конец имени. Исходник нужен
    не для правки (её он не допускает), а для чтения: инженер ОТН иногда
    выделяет на нём заменяемый участок красным, и это прямая подсказка.
    """
    папка, имя = os.path.split(filename or "")
    stem, ext = os.path.splitext(имя)
    m = _SHEET_RE.search(stem)
    if m:
        основа = stem[:m.start()]
        новое = f"{основа}.{m.group(0)}{ext}"
    else:
        новое = f"{stem}.{ext}"
    return os.path.join(папка, новое) if папка else новое


def likely_sheet(number: int, by_sheet: dict, span: int = 2) -> int | None:
    """
    Подсказка, на каком листе сечение, когда номер нашёлся на нескольких.

    Считаем соседние номера (`number−span … number+span`, сам номер не в счёт):
    сечения нумеруются вдоль трубопровода, и лист, где лежат соседи, почти
    наверняка держит и само сечение. `by_sheet` — {индекс листа: множество
    номеров на нём}.

    Возвращает индекс листа или None, если перевеса нет: подсказка не должна
    подменять решение сотрудника, она только помечает вероятный лист.
    """
    соседи = [n for n in range(number - span, number + span + 1) if n != number]
    счёт = {}
    for лист, номера in (by_sheet or {}).items():
        счёт[лист] = sum(1 for n in соседи if n in номера)
    if not счёт:
        return None
    лучший = max(счёт, key=lambda k: счёт[k])
    if счёт[лучший] == 0:
        return None
    if sum(1 for v in счёт.values() if v == счёт[лучший]) > 1:
        return None                     # ничья — подсказывать нечего
    return лучший
